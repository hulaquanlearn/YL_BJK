CREATE TABLE IF NOT EXISTS inspection_notices (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 workshop_code VARCHAR(30) NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL,
 header_json JSON NOT NULL,
 issues_json JSON NOT NULL,
 revision INT NOT NULL DEFAULT 0,
 retention_until DATE DEFAULT NULL,
 archived_at DATETIME DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_inspection_scope (workshop_code,updated_at),
 KEY idx_inspection_owner (owner_id,updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS inspection_events (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 notice_id BIGINT UNSIGNED NOT NULL,
 revision INT NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 event_type VARCHAR(40) NOT NULL,
 detail_json JSON NOT NULL,
 before_json MEDIUMTEXT DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_inspection_events_notice (notice_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS inspection_sources (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 notice_id BIGINT UNSIGNED NOT NULL,
 filename VARCHAR(180) NOT NULL,
 mime VARCHAR(30) NOT NULL,
 sha256 CHAR(64) NOT NULL,
 image MEDIUMBLOB NOT NULL,
 byte_size INT NOT NULL,
 width INT NOT NULL,
 height INT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 error_message VARCHAR(300) DEFAULT NULL,
 duplicate_of BIGINT UNSIGNED DEFAULT NULL,
 reviewed TINYINT(1) NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_inspection_source_notice (notice_id,id),
 KEY idx_inspection_source_hash (notice_id,sha256)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
