CREATE TABLE IF NOT EXISTS work_members (
 user_id BIGINT UNSIGNED PRIMARY KEY, workshop_code VARCHAR(30) NOT NULL, floor INT NOT NULL,
 active TINYINT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_reviewers (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 workshop_code VARCHAR(30) NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 assigned_by BIGINT UNSIGNED NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_work_reviewer_scope (workshop_code,active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_rules (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, workshop_code VARCHAR(30) NOT NULL,
 effective_week DATE NOT NULL, rules_json JSON NOT NULL, created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX scope_week(workshop_code,effective_week)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_reports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 week_start DATE NOT NULL, workshop_code VARCHAR(30) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'draft',
 rules_json JSON NULL, result_json JSON NULL, summary TEXT NULL, feedback TEXT NULL,
 reviewer_id BIGINT UNSIGNED NULL, revision INT NOT NULL DEFAULT 0,
 submitted_at DATETIME NULL, published_at DATETIME NULL,
 UNIQUE KEY owner_week(user_id,week_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_records (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 week_start DATE NOT NULL, record_date DATE NOT NULL, kind VARCHAR(20) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'draft', payload JSON NOT NULL,
 revision INT NOT NULL DEFAULT 0, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX owner_week(user_id,week_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_photos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, record_id BIGINT UNSIGNED NOT NULL,
 mime VARCHAR(30) NOT NULL, task_key VARCHAR(80) DEFAULT NULL, image MEDIUMBLOB NOT NULL, INDEX record_photos(record_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, report_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL, action VARCHAR(30) NOT NULL, detail JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX report_events(report_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
