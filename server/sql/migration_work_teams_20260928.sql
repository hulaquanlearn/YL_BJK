CREATE TABLE IF NOT EXISTS work_team_assignments (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 shift_leader_id BIGINT UNSIGNED NOT NULL,
 assigned_by BIGINT UNSIGNED NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY team_members (shift_leader_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_team_rules (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 shift_leader_id BIGINT UNSIGNED NOT NULL,
 effective_week DATE NOT NULL,
 rules_json JSON NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY team_week (shift_leader_id,effective_week)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_team_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 previous_leader_id BIGINT UNSIGNED NULL,
 shift_leader_id BIGINT UNSIGNED NULL,
 floor INT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
