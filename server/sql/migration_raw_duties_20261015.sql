-- 原粮周履职：仅新增独立业务表，不修改制曲考评和现有业务数据。
CREATE TABLE IF NOT EXISTS raw_duty_templates (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(100) NOT NULL, entries_json JSON NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS raw_duty_members (
 user_id BIGINT UNSIGNED NOT NULL PRIMARY KEY, reviewer_id BIGINT UNSIGNED NOT NULL,
 position_name VARCHAR(50) NOT NULL, team_name VARCHAR(80) NOT NULL DEFAULT '',
 template_id BIGINT UNSIGNED NOT NULL DEFAULT 0, active TINYINT NOT NULL DEFAULT 1,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_raw_duty_reviewer(reviewer_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS raw_duty_reports (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 week_start DATE NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'draft',
 identity_json JSON NOT NULL, template_json JSON NOT NULL, checks_json JSON NOT NULL,
 cadence_json JSON DEFAULT NULL, summary TEXT NOT NULL, feedback TEXT NOT NULL, revision INT UNSIGNED NOT NULL DEFAULT 1,
 submitted_at DATETIME NULL, reviewed_by BIGINT UNSIGNED NULL, confirmed_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_raw_duty_user_week(user_id,week_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS raw_duty_photos (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, report_id BIGINT UNSIGNED NOT NULL,
 image MEDIUMBLOB NOT NULL, mime VARCHAR(40) NOT NULL, filename VARCHAR(160) NOT NULL,
 byte_size INT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_raw_duty_photo_report(report_id),
 CONSTRAINT fk_raw_duty_photo_report FOREIGN KEY(report_id) REFERENCES raw_duty_reports(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS raw_duty_events (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, report_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL, action VARCHAR(30) NOT NULL, detail JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_raw_duty_event_report(report_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
