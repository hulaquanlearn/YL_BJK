CREATE TABLE IF NOT EXISTS attendance_reports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 workshop_code VARCHAR(30) NOT NULL DEFAULT 'raw_grain',
 title VARCHAR(180) NOT NULL,
 period CHAR(7) NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL,
 analysis_json LONGTEXT NOT NULL,
 source_hash CHAR(64) NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 0,
 retention_until DATE NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY attendance_scope(workshop_code,updated_at),
 UNIQUE KEY attendance_import(workshop_code,source_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS attendance_sources (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 report_id BIGINT UNSIGNED NOT NULL,
 source_kind VARCHAR(20) NOT NULL,
 filename VARCHAR(180) NOT NULL,
 sha256 CHAR(64) NOT NULL,
 byte_size INT UNSIGNED NOT NULL,
 content MEDIUMBLOB NOT NULL,
 UNIQUE KEY attendance_source(report_id,source_kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS attendance_notes (
 report_id BIGINT UNSIGNED NOT NULL,
 entry_key VARCHAR(160) NOT NULL,
 note VARCHAR(2000) NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(report_id,entry_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_storage_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor_id BIGINT UNSIGNED NOT NULL,
 source_kind VARCHAR(30) NOT NULL,
 source_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(180) NOT NULL,
 released_bytes BIGINT UNSIGNED NOT NULL,
 detail_json JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY storage_audit_time(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
