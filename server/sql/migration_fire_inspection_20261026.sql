-- Independent fire inspection records; no existing business data is changed.
CREATE TABLE IF NOT EXISTS fire_areas (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, active TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_fire_area_name(name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_members (
 user_id BIGINT UNSIGNED NOT NULL, area_id BIGINT UNSIGNED NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,area_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_points (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, area_id BIGINT UNSIGNED NOT NULL,
 code VARCHAR(100) NOT NULL, name VARCHAR(180) NOT NULL,
 building VARCHAR(120) NOT NULL DEFAULT '', floor VARCHAR(50) NOT NULL DEFAULT '',
 room VARCHAR(120) NOT NULL DEFAULT '', location VARCHAR(500) NOT NULL DEFAULT '',
 spatial_json JSON DEFAULT NULL, revision INT NOT NULL DEFAULT 1, active TINYINT NOT NULL DEFAULT 1,
 source_key CHAR(64) CHARACTER SET ascii DEFAULT NULL,
 created_by BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_fire_point_code(code), UNIQUE KEY uk_fire_source_key(source_key), KEY idx_fire_point_area(area_id,active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_assets (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, point_id BIGINT UNSIGNED NOT NULL,
 type VARCHAR(30) NOT NULL, code VARCHAR(100) NOT NULL DEFAULT '', name VARCHAR(180) NOT NULL,
 spec VARCHAR(160) NOT NULL DEFAULT '', quantity DECIMAL(12,3) DEFAULT NULL,
 manufactured_date VARCHAR(80) NOT NULL DEFAULT '', manufacturer VARCHAR(180) NOT NULL DEFAULT '', source_json JSON DEFAULT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'active', notes VARCHAR(1000) NOT NULL DEFAULT '',
 active TINYINT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 retired_at DATETIME DEFAULT NULL, KEY idx_fire_asset_point(point_id,active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_cycles (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, name VARCHAR(180) NOT NULL,
 deadline DATETIME DEFAULT NULL, inspection_month CHAR(7) DEFAULT NULL, status VARCHAR(20) NOT NULL DEFAULT 'open',
 created_by BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_cycle_points (
 cycle_id BIGINT UNSIGNED NOT NULL, point_id BIGINT UNSIGNED NOT NULL, area_id BIGINT UNSIGNED NOT NULL,
 snapshot_json JSON NOT NULL, PRIMARY KEY(cycle_id,point_id), KEY idx_fire_cycle_area(cycle_id,area_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_records (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, cycle_id BIGINT UNSIGNED NOT NULL,
 point_id BIGINT UNSIGNED NOT NULL, area_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL, actor_name VARCHAR(80) NOT NULL,
 actual_checked_at DATETIME NOT NULL, submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 backfill_reason VARCHAR(1000) NOT NULL DEFAULT '', result VARCHAR(20) NOT NULL,
 remark VARCHAR(2000) NOT NULL DEFAULT '', items_json JSON NOT NULL, point_snapshot JSON NOT NULL,
 request_id VARCHAR(80) CHARACTER SET ascii NOT NULL,
 KEY idx_fire_cycle_record(cycle_id,point_id), UNIQUE KEY uk_fire_record_request(actor_id,request_id),
 KEY idx_fire_record_point(point_id,submitted_at), KEY idx_fire_record_area(area_id,cycle_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_record_assets (
 cycle_id BIGINT UNSIGNED NOT NULL, point_id BIGINT UNSIGNED NOT NULL,
 asset_id BIGINT UNSIGNED NOT NULL, record_id BIGINT UNSIGNED NOT NULL, result VARCHAR(20) NOT NULL,
 PRIMARY KEY(cycle_id,asset_id), KEY idx_fire_record_asset_point(cycle_id,point_id), KEY idx_fire_record_asset_record(record_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_photos (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, point_id BIGINT UNSIGNED NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL, asset_id BIGINT UNSIGNED DEFAULT NULL, record_id BIGINT UNSIGNED DEFAULT NULL, issue_id BIGINT UNSIGNED DEFAULT NULL, issue_event_id BIGINT UNSIGNED DEFAULT NULL,
 image MEDIUMBLOB NOT NULL, mime VARCHAR(50) NOT NULL, filename VARCHAR(180) NOT NULL,
 byte_size INT UNSIGNED NOT NULL, discarded_at DATETIME DEFAULT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_fire_photo_point(point_id,owner_id), KEY idx_fire_photo_record(record_id), KEY idx_fire_photo_issue(issue_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_issues (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, record_id BIGINT UNSIGNED NOT NULL,
 point_id BIGINT UNSIGNED NOT NULL, area_id BIGINT UNSIGNED NOT NULL, cycle_id BIGINT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'open', remark VARCHAR(2000) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, resolved_at DATETIME DEFAULT NULL, closed_at DATETIME DEFAULT NULL,
 KEY idx_fire_issue_point(point_id,status), UNIQUE KEY uk_fire_issue_record(record_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_issue_events (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, issue_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL, actor_name VARCHAR(80) NOT NULL, action VARCHAR(20) NOT NULL,
 remark VARCHAR(2000) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_fire_issue_event(issue_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_admin_events (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(50) NOT NULL, detail_json JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY idx_fire_admin_event(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS fire_imports (
 id CHAR(36) CHARACTER SET ascii NOT NULL PRIMARY KEY, owner_id BIGINT UNSIGNED NOT NULL,
 filename VARCHAR(180) NOT NULL, file_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 source MEDIUMBLOB NOT NULL, preview_json JSON NOT NULL, result_json JSON DEFAULT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending', created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at DATETIME NOT NULL, KEY idx_fire_import_pending(status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
