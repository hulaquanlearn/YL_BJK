CREATE TABLE IF NOT EXISTS work_catalog_versions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 effective_week DATE NOT NULL, entries_json JSON NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY catalog_week (effective_week)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_week_schedule (
 user_id BIGINT UNSIGNED NOT NULL, week_start DATE NOT NULL, rest_date DATE NULL,
 revision INT NOT NULL DEFAULT 0, updated_by BIGINT UNSIGNED NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,week_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_tasks (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, owner_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(150) NOT NULL, instructions TEXT NOT NULL, duty_id VARCHAR(80) NULL,
 due_date DATE NOT NULL, evidence_mode VARCHAR(20) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY task_owner(owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_task_assignments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, task_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL, floor INT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'pending',
 result VARCHAR(20) NULL, note TEXT NULL, reference VARCHAR(1000) NULL,
 feedback TEXT NULL, revision INT NOT NULL DEFAULT 0,
 submitted_at DATETIME NULL, accepted_at DATETIME NULL,
 UNIQUE KEY task_person(task_id,user_id), KEY task_assignee(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_task_files (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, assignment_id BIGINT UNSIGNED NOT NULL,
 mime VARCHAR(30) NOT NULL, image MEDIUMBLOB NOT NULL,
 KEY task_files(assignment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_task_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, assignment_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL, action VARCHAR(30) NOT NULL, detail JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY task_events(assignment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS work_task_file_references (
 file_id BIGINT UNSIGNED NOT NULL, record_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(file_id,record_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
