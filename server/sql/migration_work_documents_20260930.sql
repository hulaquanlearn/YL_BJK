CREATE TABLE IF NOT EXISTS work_document_bindings (
 workshop_code VARCHAR(30) NOT NULL,
 duty_id VARCHAR(80) NOT NULL,
 document_title VARCHAR(100) NOT NULL DEFAULT '',
 document_url VARCHAR(1000) NOT NULL DEFAULT '',
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 updated_by BIGINT UNSIGNED NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(workshop_code,duty_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
